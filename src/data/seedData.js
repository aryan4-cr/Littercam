// ──────────────────────────────────────────────────────────────────────────────
export const FINE_SCHEDULE = {
  FIRST_OFFENCE_MIN: 250,
  FIRST_OFFENCE_MAX: 500,
  VEHICLE_LITTERING_FLAT: 500,
  REPEAT_2ND_MULTIPLIER: 2,
  REPEAT_3RD_MULTIPLIER: 3,
};

export function calculateFine({ type, offenceCount = 1 }) {
  if (type === 'VEHICLE_LITTERING') return FINE_SCHEDULE.VEHICLE_LITTERING_FLAT;
  const base = Math.floor(
    Math.random() * (FINE_SCHEDULE.FIRST_OFFENCE_MAX - FINE_SCHEDULE.FIRST_OFFENCE_MIN + 1) +
    FINE_SCHEDULE.FIRST_OFFENCE_MIN
  );
  if (offenceCount === 2) return base * FINE_SCHEDULE.REPEAT_2ND_MULTIPLIER;
  if (offenceCount >= 3) return base * FINE_SCHEDULE.REPEAT_3RD_MULTIPLIER;
  return base;
}

